package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const serviceImportPath = "github.com/go-ctap/kit/service"

type operationMethod struct {
	name         string
	requestType  string
	responseType string
}

func main() {
	output := flag.String("output", "ctapkit_operations.go", "generated Go file")
	flag.Parse()

	if err := run(*output); err != nil {
		log.Fatal(err)
	}
}

func run(output string) error {
	serviceDir, err := packageDir(serviceImportPath)
	if err != nil {
		return err
	}

	source, err := generate(serviceDir)
	if err != nil {
		return err
	}

	if err := os.WriteFile(output, source, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", output, err)
	}

	return nil
}

func packageDir(importPath string) (string, error) {
	command := exec.Command("go", "list", "-f={{.Dir}}", importPath)
	var stderr bytes.Buffer
	command.Stderr = &stderr

	output, err := command.Output()
	if err != nil {
		return "", fmt.Errorf("locate %s: %w: %s", importPath, err, strings.TrimSpace(stderr.String()))
	}

	dir := strings.TrimSpace(string(output))
	if dir == "" {
		return "", fmt.Errorf("locate %s: go list returned an empty directory", importPath)
	}

	return dir, nil
}

func generate(serviceDir string) ([]byte, error) {
	sourcePath := filepath.Join(serviceDir, "operations.go")
	fileSet := token.NewFileSet()
	file, err := parser.ParseFile(fileSet, sourcePath, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", sourcePath, err)
	}
	if file.Name.Name != "service" {
		return nil, fmt.Errorf("parse %s: package is %q, want service", sourcePath, file.Name.Name)
	}

	methods := make([]operationMethod, 0)
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Recv == nil || !function.Name.IsExported() || !isServiceReceiver(function.Recv) {
			continue
		}

		method, err := parseOperationMethod(function)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", serviceImportPath, function.Name.Name, err)
		}
		methods = append(methods, method)
	}
	if len(methods) == 0 {
		return nil, fmt.Errorf("parse %s: no exported methods on *Service", sourcePath)
	}

	var output bytes.Buffer
	output.WriteString("// Code generated by internal/cmd/genctapkitoperations; DO NOT EDIT.\n\n")
	output.WriteString("package main\n\n")
	output.WriteString("import (\n")
	output.WriteString("\t\"context\"\n\n")
	output.WriteString("\tkitservice \"github.com/go-ctap/kit/service\"\n")
	output.WriteString(")\n")

	for _, method := range methods {
		fmt.Fprintf(
			&output,
			"\nfunc (s *CtapkitService) %s(ctx context.Context, req kitservice.%s) (kitservice.%s, error) {\n\treturn s.core.%s(ctx, req)\n}\n",
			method.name,
			method.requestType,
			method.responseType,
			method.name,
		)
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated operations: %w", err)
	}

	return formatted, nil
}

func isServiceReceiver(receivers *ast.FieldList) bool {
	if receivers == nil || len(receivers.List) != 1 {
		return false
	}

	pointer, ok := receivers.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}

	receiver, ok := pointer.X.(*ast.Ident)
	return ok && receiver.Name == "Service"
}

func parseOperationMethod(function *ast.FuncDecl) (operationMethod, error) {
	if function.Type.TypeParams != nil && len(function.Type.TypeParams.List) != 0 {
		return operationMethod{}, fmt.Errorf("generic methods are not supported")
	}

	parameters := function.Type.Params.List
	if len(parameters) != 2 || !singleParameterNamed(parameters[0], "ctx") || !singleParameterNamed(parameters[1], "req") {
		return operationMethod{}, fmt.Errorf("want parameters (ctx context.Context, req Request)")
	}
	if !isSelector(parameters[0].Type, "context", "Context") {
		return operationMethod{}, fmt.Errorf("first parameter is not context.Context")
	}

	request, ok := parameters[1].Type.(*ast.Ident)
	if !ok || !request.IsExported() {
		return operationMethod{}, fmt.Errorf("request type must be an exported service identifier")
	}

	if function.Type.Results == nil || len(function.Type.Results.List) != 2 {
		return operationMethod{}, fmt.Errorf("want results (Envelope, error)")
	}
	responseField := function.Type.Results.List[0]
	errorField := function.Type.Results.List[1]
	if len(responseField.Names) != 0 || len(errorField.Names) != 0 {
		return operationMethod{}, fmt.Errorf("named results are not supported")
	}

	response, ok := responseField.Type.(*ast.Ident)
	if !ok || !response.IsExported() {
		return operationMethod{}, fmt.Errorf("response type must be an exported service identifier")
	}
	resultError, ok := errorField.Type.(*ast.Ident)
	if !ok || resultError.Name != "error" {
		return operationMethod{}, fmt.Errorf("second result is not error")
	}

	return operationMethod{
		name:         function.Name.Name,
		requestType:  request.Name,
		responseType: response.Name,
	}, nil
}

func singleParameterNamed(field *ast.Field, name string) bool {
	return len(field.Names) == 1 && field.Names[0].Name == name
}

func isSelector(expression ast.Expr, packageName, name string) bool {
	selector, ok := expression.(*ast.SelectorExpr)
	if !ok || selector.Sel.Name != name {
		return false
	}

	identifier, ok := selector.X.(*ast.Ident)
	return ok && identifier.Name == packageName
}
